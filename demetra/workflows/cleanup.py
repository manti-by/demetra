PR_BODY_FENCE_LANGUAGES = ("", "markdown", "md")


def _unwrap_pr_body(body: str) -> str:
    """Return the PR body without a surrounding markdown code fence.

    The description is generated by an LLM that occasionally answers with the
    whole body inside a single fenced block, which GitHub renders as a code
    block. Only a body that starts and ends with a matching fence (three or
    more backticks, the closing one at least as long as the opening) in an
    empty, markdown or md language is unwrapped. Interior fences shorter than
    the opening delimiter are nested code samples and stay in the description;
    an interior fence at least as long as the opening would close the block
    early, so such a body is left untouched. An empty unwrapped body is also
    left untouched, so the PR is always created with a nonempty description.
    A strip is reported to the session log.

    Args:
        body: The generated PR description.

    Returns:
        str: The description with any surrounding fence removed and stripped.
    """
    text = body.strip()
    lines = text.splitlines()
    if len(lines) < 2:
        return text
    opening, closing = lines[0].strip(), lines[-1].strip()
    if not opening.startswith("```"):
        return text
    opening_length = len(opening) - len(opening.lstrip("`"))
    if opening_length < 3 or set(closing) != {"`"} or len(closing) < opening_length:
        return text
    if any(line.strip().startswith("`" * opening_length) for line in lines[1:-1]):
        return text
    if opening[opening_length:].strip().casefold() not in PR_BODY_FENCE_LANGUAGES:
        return text
    unwrapped = "\n".join(lines[1:-1]).strip()
    if not unwrapped:
        return text
    print_message("Stripped markdown code fence from PR description", style="info")
    return unwrapped


async def commit_and_push(context: Context) -> bool:
    """Commit, push and open a pull request for the current branch.

    Stages the build changes, generates the session wiki page into the
    worktree (so it is part of the same commit), stages the wiki files, commits
    with the task title, pushes the branch, generates a PR description, creates
    the PR and records the PR link and final session step. A markdown code fence
    wrapped around the generated description is unwrapped, so chat and Linear
    sessions both open the PR with a plain body.

    Args:
        context: The workflow context.

    Returns:
        bool: True when the PR was created, False when there were no files to
            commit.

    Raises:
        PullRequestError: When the PR creation fails.
    """
    print_message("Committing changes", style="heading")

    has_files = await git_add_all(
        target_path=context.worktree_path, environment=context.environment, project_id=context.project.id
    )
    if not has_files:
        print_message("No files to commit, looping back to build agent", style="warning")
        return False

    print_message("Generating wiki page", style="heading")
    await update_session_step(task_id=context.linear_task.id, step="wiki")
    await record_session_step(task_id=context.linear_task.id, step="wiki")
    wiki_error: WikiError | None = None
    try:
        await write_session_wiki_page(context=context, wiki_root=context.worktree_path / "wiki")
    except WikiError as e:
        wiki_error = e
    except Exception as e:  # noqa: BLE001
        wiki_error = WikiError(f"Failed to write wiki page: {e}")
        wiki_error.__cause__ = e
    if wiki_error is None:
        if not await git_add_all(
            target_path=context.worktree_path, environment=context.environment, project_id=context.project.id
        ):
            print_message("No files to commit after wiki page generation, looping back to build agent", style="warning")
            return False
    else:
        print_message(
            f"Wiki page generation failed: {wiki_error}, committing build changes without wiki page",
            style="warning",
        )

    await update_session_step(task_id=context.linear_task.id, step="push")
    await record_session_step(task_id=context.linear_task.id, step="push")
    await git_commit(
        target_path=context.worktree_path,
        message=context.linear_task.full_title,
        environment=context.environment,
        project_id=context.project.id,
    )

    print_message("Pushing changes", style="heading")
    await git_push(
        target_path=context.worktree_path,
        branch_name=context.branch_name,
        environment=context.environment,
        project_id=context.project.id,
    )

    print_message("Generating PR description", style="heading")
    task_details = f"{context.linear_task.full_title}\n\n{context.linear_task.description}"
    try:
        pr_body = await generate_pr_description(
            task_details=task_details,
            build_plan=context.build_plan,
            task_id=context.linear_task.id,
            environment=context.environment,
        )
    except PrDescriptionError as e:
        raise PullRequestError(f"Failed to generate PR description: {e}") from e
    pr_body = _unwrap_pr_body(pr_body)
    if not pr_body:
        pr_body = ""

    print_message("Creating GitHub PR", style="heading")

    exit_code, stdout, stderr = await create_pull_request(
        target_path=context.worktree_path,
        branch_name=context.branch_name,
        title=context.linear_task.full_title,
        body=pr_body,
        environment=context.environment,
        project_id=context.project.id,
    )
    if exit_code != 0:
        raise PullRequestError(f"Failed to create PR: {stderr or stdout}")

    print_message(stdout.strip(), style="result")

    if pr_link := extract_pr_link(stdout):
        try:
            await update_session_pr_link(task_id=context.linear_task.id, pr_link=pr_link)
        except SQLAlchemyError:
            print_message("Failed to persist PR link, continuing.", style="warning")

    if not context.is_chat:
        await update_session_step(task_id=context.linear_task.id, step="completed")
    await record_session_step(task_id=context.linear_task.id, step="completed")

    if wiki_error is not None:
        print_message(
            f"Wiki page generation failed ({wiki_error}); commit and PR succeeded without wiki page",
            style="warning",
        )

    return True


async def cleanup_workflow(
    context: Context,
    is_success: bool,
    should_update_linear_status: bool,
    failure_step: str = "failed",
    failure_message: str | None = None,
) -> None:
    """Finalize a workflow run: record the terminal step, clean up git and update Linear.

    On failure the session step is advanced and a ``kind='step'`` history row is
    recorded under ``failure_step``, carrying ``failure_message`` as the reason
    context shown in session history. Chat sessions keep their worktree and
    branch, and the ``GIT_DISABLE_WORKTREE_REMOVAL`` flag keeps them for every
    session, so a rerun continues the same code; otherwise the worktree is
    removed. When requested, the Linear ticket is moved according to the
    outcome. Removing the worktree invalidates any primary agent session marker
    (history still resolves by ``task_id``, so nothing is hidden); a preserved
    worktree keeps its marker, because the session is still resolvable.

    Chat-mode terminal steps are published only after the worktree cleanup, so a
    resume request can never start a new run while the previous one is still
    removing its worktree. A cleanup failure publishes the failure step (in a
    ``finally`` block) instead of leaving the session at an active step or
    reporting success; a worktree that could not be removed keeps the run from
    being published as ``completed``.

    Args:
        context: The workflow context.
        is_success: Whether the workflow completed successfully.
        should_update_linear_status: Whether to move the Linear ticket.
        failure_step: Step name to record on failure.
        failure_message: Failure reason to record with the failure step row.
    """
    if not is_success and not context.is_chat:
        await update_session_step(task_id=context.linear_task.id, step=failure_step)
        await record_session_step(task_id=context.linear_task.id, step=failure_step, message=failure_message)

    remove_worktree = not (context.is_chat or GIT["disable_worktree_removal"])
    worktree_cleaned = False
    cleanup_succeeded = False
    try:
        worktree_cleaned = await git_cleanup(context=context, is_success=is_success, remove_worktree=remove_worktree)
        if not context.is_research and remove_worktree:
            await invalidate_agent_sessions(task_id=context.linear_task.id)
        if should_update_linear_status and not context.is_chat:
            await linear_cleanup(context=context, is_success=is_success)
        cleanup_succeeded = worktree_cleaned
    finally:
        if context.is_chat:
            if is_success and cleanup_succeeded:
                if not context.is_research:
                    await update_session_step(task_id=context.linear_task.id, step="completed")
            else:
                await update_session_step(task_id=context.linear_task.id, step=failure_step)
                await record_session_step(task_id=context.linear_task.id, step=failure_step, message=failure_message)
